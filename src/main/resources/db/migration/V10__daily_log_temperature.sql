-- =====================================================================
-- 일지 온도 구간 (복지관 요청: 날씨 표현에 온도 추가)
-- - 정확한 온도가 아니라 구간 하나를 고른다
--     COLD 추움(10℃ 이하) / COOL 선선함(11~19℃) / WARM 따뜻함(20~27℃) / HOT 더움(28℃ 이상)
-- - 비워 둘 수 있다. 이 칸이 생기기 전 일지에는 온도가 없다 (통계에서는 따로 세어 알려 준다)
-- - 구간은 4개로 고정이라 목록 테이블 대신 CHECK로 막는다. 이름·설명은 서버 TemperatureBand에 있다
-- =====================================================================
ALTER TABLE daily_log
    ADD COLUMN temperature VARCHAR(10)
        CHECK (temperature IN ('COLD', 'COOL', 'WARM', 'HOT'));
